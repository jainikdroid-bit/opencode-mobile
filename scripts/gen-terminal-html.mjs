// Builds src/lib/terminal-html.ts: a single self-contained HTML page (xterm.js + fit addon
// inlined) that the Terminal screen loads into a WebView. Run after changing the page below
// or upgrading @xterm/*:   node scripts/gen-terminal-html.mjs
import { readFile, writeFile } from "node:fs/promises"

const xtermJs = await readFile("node_modules/@xterm/xterm/lib/xterm.js", "utf8")
const xtermCss = await readFile("node_modules/@xterm/xterm/css/xterm.css", "utf8")
const fitJs = await readFile("node_modules/@xterm/addon-fit/lib/addon-fit.js", "utf8")

// Messages page -> app:  {t:"ready"} | {t:"input", d} | {t:"resize", cols, rows}
// Messages app -> page:  window.termWrite(text), window.termFocus(), window.termClear(), window.termSetFont(px)
const page = `
const term = new Terminal({
  fontFamily: "Menlo, Consolas, 'DejaVu Sans Mono', monospace",
  fontSize: 13,
  cursorBlink: true,
  scrollback: 5000,
  allowProposedApi: true,
  // Display only: typing goes through the app's own input field. xterm's hidden textarea
  // double-sends characters with Android IME composition.
  disableStdin: true,
  theme: { background: "#0b0b0f", foreground: "#e5e7eb", cursor: "#a78bfa", selectionBackground: "#4c3a8a" },
})
const fit = new FitAddon.FitAddon()
term.loadAddon(fit)
term.open(document.getElementById("t"))
if (term.textarea) { term.textarea.setAttribute("inputmode", "none"); term.textarea.setAttribute("readonly", "readonly") }
function post(message) { window.ReactNativeWebView.postMessage(JSON.stringify(message)) }
function refit() {
  try { fit.fit() } catch (e) {}
  post({ t: "resize", cols: term.cols, rows: term.rows })
}
term.onData((d) => post({ t: "input", d }))
window.addEventListener("resize", refit)
window.termWrite = (s) => term.write(s)
window.termFocus = () => term.focus()
window.termClear = () => term.clear()
window.termSetFont = (px) => { term.options.fontSize = px; refit() }
refit()
post({ t: "ready" })
`

const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>${xtermCss}
html,body{margin:0;height:100%;background:#0b0b0f;overflow:hidden}
#t{position:absolute;inset:0;padding:4px}
</style></head><body><div id="t"></div>
<script>${xtermJs}</script>
<script>${fitJs}</script>
<script>${page}</script>
</body></html>`

const out = `// GENERATED by scripts/gen-terminal-html.mjs. Do not edit by hand.
export const TERMINAL_HTML: string = ${JSON.stringify(html)}
`
await writeFile("src/lib/terminal-html.ts", out)
console.log(`wrote src/lib/terminal-html.ts (${(out.length / 1024).toFixed(0)} KB)`)
